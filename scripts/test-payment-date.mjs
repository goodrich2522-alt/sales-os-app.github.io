// scripts/test-payment-date.mjs — อ่าน "วันที่รับเงิน" จากไฟล์บัญชี
//
// ที่มา (27 พ.ย. 2569 · เจ้าของถามว่า "ได้เงินแล้ว ทำไมข้อมูลการรับเงินไม่เข้าแอป"):
// ตรวจไฟล์ตุลาคมแล้วพบว่าบัญชีพิมพ์หมายเหตุต่อท้ายในช่องวันที่ เช่น
//   "13/11/2569 รอชนสเตทเม้น"   ← เงินเข้าแล้ว แต่ของเดิมอ่านไม่ออก (บังคับเป็นวันที่ล้วน)
//   "นัดชำระ 15/11/2569"        ← ยังไม่ได้เงิน ห้ามเอามาใช้เด็ดขาด
// เส้นแบ่งนี้สำคัญกว่าตัวการอ่าน: ดึงผิดด้านเดียว = จ่ายค่าคอมก่อนเงินเข้า
//
// รัน: node scripts/test-payment-date.mjs
import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createRequire } from "node:module";

const out = mkdtempSync(join(tmpdir(), "paydate-"));
const cleanup = () => rmSync(out, { recursive: true, force: true });
const req = createRequire(import.meta.url);
try {
  execFileSync(process.execPath, [req.resolve("typescript/bin/tsc"),
    "lib/paymentImport.ts",
    "--outDir", out, "--module", "commonjs", "--target", "es2022", "--moduleResolution", "node", "--skipLibCheck"],
    { stdio: "pipe" });
} catch (e) {
  console.error("คอมไพล์ lib/paymentImport.ts ไม่ผ่าน:\n" + String(e.stdout || e.message).slice(0, 1000));
  cleanup();
  process.exit(1);
}
const { toIsoDate, normName } = req(join(out, "paymentImport.js"));

const cases = [];
const check = (name, ok, why = "") => cases.push([name, !!ok, why]);
const d = (v) => toIsoDate(v);

// ── รูปแบบปกติที่เคยรองรับอยู่แล้ว (กันแก้แล้วพัง) ────────────────────────
check("1) วว/ดด/ปปปป ค.ศ.", d("01/07/2026") === "2026-07-01", "ได้ " + d("01/07/2026"));
check("2) วว/ดด/ปปปป พ.ศ. → แปลงเป็น ค.ศ.", d("13/11/2569") === "2026-11-13", "ได้ " + d("13/11/2569"));
check("3) ปปปป-ดด-วว", d("2569-07-01") === "2026-07-01", "ได้ " + d("2569-07-01"));
check("4) ดด/วว/ปป (รูปแบบที่ Excel แสดง)", d("6/29/69") === "2026-06-29", "ได้ " + d("6/29/69"));

// ⭐ รูที่ทำให้ "ได้เงินแล้วแต่แอปไม่รู้"
check("5) มีหมายเหตุต่อท้ายวันที่ → ต้องยังอ่านวันออกมาได้",
  d("13/11/2569 รอชนสเตทเม้น") === "2026-11-13",
  'ได้ "' + d("13/11/2569 รอชนสเตทเม้น") + '" — เงินเข้าแล้วแต่ระบบมองไม่เห็น ค่าคอมค้าง');

check("6) หมายเหตุหลายคำก็ยังอ่านได้",
  d("20/10/2026 โอนเข้า BAY เช้า") === "2026-10-20",
  "ได้ " + d("20/10/2026 โอนเข้า BAY เช้า"));

// ── ตัวคุม: ของที่ "ยังไม่ได้เงิน" ห้ามถูกอ่านเป็นวันรับเงิน ────────────────
for (const [txt, label] of [
  ["นัดชำระ 15/11/2569", "นัดชำระ"],
  ["ครบกำหนด 22/10/2026", "ครบกำหนด"],
  ["รอโอน 30/11/2569", "รอโอน"],
  ["คาดว่าจะชำระ 01/12/2569", "คาดว่าจะชำระ"],
]) {
  check(`7.${label}) "${txt}" → ต้องไม่นับเป็นวันรับเงิน (ตัวคุม)`, d(txt) === "",
    `ได้ "${d(txt)}" — บันทึกว่ารับเงินแล้วทั้งที่ยังไม่ได้รับ = จ่ายค่าคอมก่อนเงินเข้า`);
}

check("8) ช่องว่าง → ไม่มีวันรับเงิน (ตัวคุม)", d("") === "" && d("   ") === "", "เดาวันจากช่องว่าง");
check("9) ข้อความล้วนไม่มีวันที่ → ไม่เดา (ตัวคุม)",
  d("รอชนสเตทเม้น") === "" && d("ยังไม่ได้รับ") === "", "เดาวันจากข้อความที่ไม่มีวันที่");
check("10) ตัวเลขมั่ว ไม่ใช่วันที่ → ไม่เดา (ตัวคุม)",
  d("12345678901234") === "", 'ได้ "' + d("12345678901234") + '"');

// ── ชื่อลูกค้า (ใช้จับคู่ใบเสร็จกับดีล) ────────────────────────────────────
check("11) ชื่อบริษัทต่างรูปแบบต้องถือว่าเป็นเจ้าเดียวกัน",
  normName("บริษัท ไทยเทพรส จำกัด (มหาชน)") === normName("ไทยเทพรส"),
  `"${normName("บริษัท ไทยเทพรส จำกัด (มหาชน)")}" vs "${normName("ไทยเทพรส")}"`);

let fail = 0;
for (const [name, ok, why] of cases) { console.log(`${name}: ${ok ? "✓" : "✗ " + why}`); if (!ok) fail++; }
console.log(fail === 0 ? `\nผ่านทั้งหมด ${cases.length}/${cases.length} ข้อ` : `\n✗ ไม่ผ่าน ${fail}/${cases.length} ข้อ`);
cleanup();
process.exitCode = fail === 0 ? 0 : 1;
