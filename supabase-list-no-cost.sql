-- supabase-list-no-cost.sql — รายชื่อรถที่ยังไม่มีราคาทุน (ไว้กรอกทุนใน Excel)
--
-- ที่มา (21 ต.ค. 2569): ในแอปมี 333 คันที่ทุนยังเป็น 0 เจ้าของต้องการไฟล์ไปลงทุนเอง
--
-- อ่านอย่างเดียว ไม่แก้ข้อมูล
-- ชื่อคอลัมน์ตรวจกับตารางจริงแล้ว: forklifts."SN" · cost_price · pi_no · received_date
--
-- วิธีใช้: Supabase → SQL Editor → วาง → Run → ปุ่ม Export → CSV
-- เรียงตามเลข PI เพื่อให้กรอกไล่ตามใบกำกับภาษีทีละใบได้เลย
--
-- ⚠️ กรอกเสร็จแล้ว **ห้ามเอาไปอัปโหลดผ่านปุ่ม "อัปโหลดหลายคัน" ในหน้าสต็อก**
--    ปุ่มนั้นมีไว้เพิ่มรถใหม่ ถ้า SN ซ้ำของเดิมมันจะสร้างรถคันใหม่เป็น SN#2 (รถซ้ำ 333 คัน)
--    ให้ส่งไฟล์ที่กรอกแล้วกลับมา จะแปลงเป็นคำสั่งอัปเดตที่เติมเฉพาะคันที่ทุนยังเป็น 0 ให้

select
  f."SN"                                          as sn,
  f.brand                                         as ยี่ห้อ,
  f.model                                         as รุ่น,
  f.vehicle_category                              as หมวดรถ,
  f.capacity_kg                                   as น้ำหนักยก_กก,
  f.pi_no                                         as เลข_pi,
  f.received_date                                 as วันรับรถ,
  f.status                                        as สถานะ,
  null::numeric                                   as ราคาทุน_กรอกตรงนี้,
  f.id                                            as รหัสรถ_ห้ามแก้
from public.forklifts f
where coalesce(f.cost_price, 0) = 0
order by
  -- รถที่ขายไปแล้วสำคัญกว่า (กระทบกำไร/ค่าคอมทันที) แล้วค่อยไล่ตาม PI
  case when f.status in ('ปิดการขายแล้ว', 'ส่งมอบแล้ว', 'ขายแล้ว') then 0 else 1 end,
  f.pi_no nulls last,
  f."SN";


