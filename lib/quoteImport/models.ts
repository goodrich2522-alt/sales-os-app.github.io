// lib/quoteImport/models.ts — "ความจำ" ของแอปเรื่องรหัสรุ่นรถ
//
// ⭐ ที่เดียวที่เก็บรูปแบบรหัสรุ่น — parser ทุกตัว (HELI / HANGCHA / ใบกำกับภาษี) ใช้ร่วมกัน
//    เจอรุ่นใหม่ที่ระบบอ่านไม่ออก → **แก้ที่ไฟล์นี้ไฟล์เดียว** แล้วเพิ่มใบนั้นเข้าชุดทดสอบ
//    (อาการ: หน้านำเข้าขึ้น "อ่านไม่พบรายการรถ" ทั้งที่ไฟล์อ่านข้อความได้)
//
// ── บทเรียนที่เคยพลาด ──
// 12 ก.ย. 2569: ใบ C20726201-132 รุ่น **CQDM15-810** อ่านไม่ออก → หน้านำเข้าขึ้น "อ่านไม่พบรายการรถ"
//   เพราะ regex เดิมบังคับให้ตัวเลขตามหลังคำนำหน้าทันที (CQD + 15)
//   แต่รหัสรุ่นจริงมี **ตัวอักษรบอกประเภทย่อย** คั่นอยู่ (CQD + M + 15)
//   ⚠️ CQDM **ไม่ใช่รุ่นพิมพ์ผิด** — เป็นรถคนละประเภทกับ CQD (ผู้ใช้ยืนยัน 12 ก.ย. 2569)
//     CQD  = Reach Truck (รถ Reach นั่งขับ)
//     CQDM = Reach Stacker แบบมีแท่นยืน + แขนจับ (Platform and arms) เช่น CQDM15-810
//   → กติกา: ตัวอักษรหลังคำนำหน้าคือ "ประเภทย่อย" ห้ามถือว่าเป็นความผิดพลาด
//     เจอตัวอักษรแปลกๆ หลังคำนำหน้า ให้รับไว้ก่อน แล้วมาบันทึกความหมายไว้ที่นี่
//
// รูปแบบรหัสรุ่น: <คำนำหน้า><อักษรรุ่นย่อย 0-2 ตัว><พิกัดยก><ส่วนขยาย>
//   CPCD30-Q22K2 · CBD20J-LI-S · CQDM15-810 · CPD25-XAJ4-I · XF35 · CBS15J

/** คำนำหน้ารหัสรุ่นที่ระบบรู้จัก — เรียง "ยาวก่อนสั้น" เสมอ (CPCD ต้องมาก่อน CPD ไม่งั้นจับได้แค่ CPD) */
export const MODEL_PREFIXES = [
  "CPCD",  // รถยกดีเซล (HELI/HANGCHA)
  "CPD",   // รถยกไฟฟ้า
  "PCD",   // รถยกไฟฟ้า (รุ่นเก่า)
  "CBD",   // รถลากพาเลท (Pallet Truck)
  "CDD",   // รถยกสูง (Stacker)
  "CQD",   // Reach Truck · ต่อด้วย M (CQDM) = Reach Stacker มีแท่นยืน+แขนจับ — คนละประเภทกัน
  "CBS",   // กึ่งไฟฟ้า (semi-electric)
  "XF",    // HANGCHA ตระกูล XF
] as const;

/**
 * regex จับรหัสรุ่น — ส่ง flags ที่ต้องการ ("i" หาอันแรก · "gi" หาทั้งหมด)
 * สร้างใหม่ทุกครั้งเพราะ regex ที่มี flag g จำตำแหน่ง lastIndex (ใช้ร่วมกันแล้วพลาด)
 */
export const modelRe = (flags = "i") =>
  new RegExp(String.raw`\b((?:${MODEL_PREFIXES.join("|")})[A-Z]{0,2}\d{1,3}[A-Z0-9-]*)`, flags);

/** พิกัดยกจากรหัสรุ่น เช่น CQDM15-810 → "1.5 ตัน" · CPCD30-Q22K2 → "3.0 ตัน" */
export function capacityFromModel(model: string): string | undefined {
  // ข้ามตัวอักษรนำหน้าก่อนค่อยอ่านตัวเลข — กันไปเจอตัวเลขในส่วนขยาย
  const n = model.replace(new RegExp(`^(?:${MODEL_PREFIXES.join("|")})[A-Z]{0,2}`, "i"), "").match(/^\d{1,3}/)?.[0]
    ?? model.match(/\d{1,3}/)?.[0];
  return n ? `${(Number(n) / 10).toFixed(1)} ตัน` : undefined;
}
