// lib/brands.ts — ชื่อพ้องยี่ห้อ (ใช้ตอนทำรายงาน ไม่แตะข้อมูลเดิมในฐานข้อมูล)
//
// ⚠️ ที่มา (22 ก.ย. 2569 · ผู้ใช้ยืนยัน): **ROCKMAN = ยี่ห้อ** · **CNC = ชื่อบริษัทผู้ขาย** (cnc-moving)
//    ข้อมูลเก่าบางชุดกรอก "ชื่อบริษัท" ไว้ในช่องยี่ห้อ (13 คัน: SDA / PD / BFG / DG2001 ฯลฯ)
//    ถ้าไม่รวมให้ รายงานจะแยกเป็นสองกอง — สัดส่วนยี่ห้อ/รุ่นขายดี/วางแผนสั่งสต็อกเพี้ยนทั้งหมด
//
// กติกา: ใช้ normBrand() ทุกที่ที่ "นับรวม/จัดกลุ่ม/กรอง" ยี่ห้อ
//        ห้ามใช้ตอน **บันทึก** ข้อมูล — ค่าที่เก็บในฐานข้อมูลคงไว้ตามที่คนกรอกจริง

/** ชื่อที่คนกรอก (ตัวพิมพ์ใหญ่) → ชื่อยี่ห้อจริง */
export const BRAND_ALIASES: Record<string, string> = {
  CNC: "ROCKMAN",          // CNC = บริษัทผู้ขายของยี่ห้อ ROCKMAN
  "CNC MOVING": "ROCKMAN",
  "CNC-MOVING": "ROCKMAN",
};

/** แปลงชื่อยี่ห้อให้เป็นชื่อจริง (ชื่อพ้อง → ยี่ห้อหลัก) · ค่าว่างคืนค่าว่าง */
export function normBrand(brand?: string | null): string {
  const s = String(brand ?? "").trim();
  if (!s) return "";
  return BRAND_ALIASES[s.toUpperCase()] ?? s;
}
