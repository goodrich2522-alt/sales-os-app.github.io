// เดิมมีตัวแปลงซ้ำกัน 2 ที่ (AppContext กับหน้าสต็อก) และตัวในหน้าสต็อกแปลงไม่ครบ
// → ดีลที่ปิดแล้วถูกมองว่า "สถานะรถไม่ตรงกับดีล" ทั้งที่ตรง และปุ่มแก้จะเขียน
//   คำว่า "ปิดการขาย/จัดส่งแล้ว" ลงช่องสถานะรถ ซึ่งไม่ใช่ค่าที่ตัวนับสต็อกรู้จัก
// (พบ 25 ก.ย. 2569 จากการ์ดรถ 05025DU4873)

import type { Sale } from "./types";

const t = (v: unknown) => String(v ?? "").trim();

/** สถานะรถที่ควรเป็น ตามใบขายใบนี้ */
export function stockStatusForSale(s: Pick<Sale, "sale_status" | "payment_type">): string {
  const st = t(s.sale_status);
  const pay = t(s.payment_type);
  const isFin = pay.includes("ไฟแนนซ์") || st.includes("ไฟแนนซ์");
  if (!st || st === "ขายแล้ว" || st.includes("ปิดการขาย") || st.includes("จัดส่งแล้ว") || st.includes("ส่งมอบ")) return "ปิดการขายแล้ว";
  if (st === "คืนสินค้า") return "พร้อมขาย";                      // ลูกค้าคืนของ → กลับเข้าคลัง
  if (st === "จอง" || st === "จอง/รอโอน" || st === "จองมัดจำ") return "ติดจอง (รอโอนมัดจำ)";
  if (st.includes("มัดจำ") || st.includes("ไฟแนนซ์") || st === "รอจัดส่ง") return isFin ? "มัดจำแล้ว/ไฟแนนซ์" : "มัดจำแล้ว/เงินสด";
  return st;
}
